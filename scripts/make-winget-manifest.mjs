#!/usr/bin/env node
/**
 * Generates the winget manifests for a release.
 *
 * Why bother: `winget install` is the only channel where an **unsigned** build
 * never shows SmartScreen. winget downloads the installer itself and marks it
 * ZoneId=2 (trusted) instead of ZoneId=3 (internet), and the dialog is triggered
 * by that zone — not by the signature. A browser download keeps the dialog until
 * the exe is signed *and* has reputation.
 *
 * Manifest set (schema 1.6, the current one at winget-pkgs):
 *   BalaRmack.VerdantLauncher.yaml            — version / default locale / installer
 *   BalaRmack.VerdantLauncher.installer.yaml  — URL, SHA-256, silent switches
 *   BalaRmack.VerdantLauncher.locale.*.yaml   — descriptions (ru-RU, en-US)
 *
 * Usage:
 *   node scripts/make-winget-manifest.mjs --version 1.2.0 --sha256 <hash> [--out dist-winget]
 */
import { createHash } from 'node:crypto'
import { createReadStream } from 'node:fs'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

export const PACKAGE_IDENTIFIER = 'BalaRmack.VerdantLauncher'
export const PACKAGE_NAME = 'Verdant Launcher'
export const PUBLISHER = 'BalaRmack'
export const GITHUB_REPO = 'BalaRmack/html-editor1'
// Full schema version: the manifest schema regex demands major.minor.patch.
export const MANIFEST_VERSION = '1.6.0'

/** `Verdant-Launcher-1.2.0-Setup.exe` — the artifact the release uploads. */
export function installerFileName(version) {
  return `Verdant-Launcher-${version}-Setup.exe`
}

export function installerUrl(version, repo = GITHUB_REPO) {
  return `https://github.com/${repo}/releases/download/v${version}/${installerFileName(version)}`
}

/** YAML scalar: winget manifests are read by several tools, keep them quoted. */
const q = (value) => `'${String(value).replace(/'/g, "''")}'`

/**
 * Builds the three manifest files as `{ name, content }` pairs.
 *
 * `--silent --no-launch` is deliberate: a package manager install must not pop
 * the launcher in the user's face, and the bootstrapper understands both flags.
 */
export function buildManifests({ version, sha256, installerSize }) {
  const url = installerUrl(version)
  const fileName = installerFileName(version)

  const versionManifest = `# Generated by scripts/make-winget-manifest.mjs — do not edit by hand.
PackageIdentifier: ${PACKAGE_IDENTIFIER}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: '${MANIFEST_VERSION}'
`

  const installerManifest = `# Generated by scripts/make-winget-manifest.mjs — do not edit by hand.
PackageIdentifier: ${PACKAGE_IDENTIFIER}
PackageVersion: ${version}
InstallerLocale: ru-RU
Platform:
  - Windows.Desktop
MinimumOSVersion: 10.0.17763.0
InstallerType: exe
Scope: user
InstallModes:
  - silent
  - silentWithProgress
UpgradeBehavior: install
ReleaseDate: ${new Date().toISOString().slice(0, 10)}
Installers:
  - Architecture: x64
    InstallerUrl: ${url}
    InstallerSha256: ${sha256.toUpperCase()}
    InstallerSwitches:
      Silent: --silent --no-launch
      SilentWithProgress: --silent --no-launch
    # No ProductCode: the entry is a plain HKCU registry key, and winget matches
    # it by DisplayName/Publisher — a fake product code would only confuse it.
    AppsAndFeaturesEntries:
      - DisplayName: ${q(PACKAGE_NAME)}
        Publisher: ${q(PUBLISHER)}
        DisplayVersion: ${version}
ManifestType: installer
ManifestVersion: '${MANIFEST_VERSION}'
`

  const russianLocale = `# Generated by scripts/make-winget-manifest.mjs — do not edit by hand.
PackageIdentifier: ${PACKAGE_IDENTIFIER}
PackageVersion: ${version}
PackageLocale: ru-RU
Publisher: ${q(PUBLISHER)}
PublisherUrl: https://github.com/${GITHUB_REPO}
PublisherSupportUrl: https://github.com/${GITHUB_REPO}/issues
PackageName: ${q(PACKAGE_NAME)}
PackageUrl: https://github.com/${GITHUB_REPO}
License: MIT
LicenseUrl: https://github.com/${GITHUB_REPO}/blob/main/LICENSE
ShortDescription: ${q('Лаунчер Minecraft: Vanilla, Fabric, Quilt, Forge и NeoForge')}
Description: >-
  Тёмный лаунчер Minecraft с изолированными сборками, менеджером контента Modrinth,
  офлайн-профилем, собственным установщиком на Electron и принудительным зеркалом
  BMCLAPI для библиотек и ассетов.
Tags:
  - minecraft
  - launcher
  - fabric
  - forge
  - modrinth
ReleaseNotesUrl: https://github.com/${GITHUB_REPO}/releases/tag/v${version}
ManifestType: locale
ManifestVersion: '${MANIFEST_VERSION}'
`

  const englishLocale = `# Generated by scripts/make-winget-manifest.mjs — do not edit by hand.
PackageIdentifier: ${PACKAGE_IDENTIFIER}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: ${q(PUBLISHER)}
PublisherUrl: https://github.com/${GITHUB_REPO}
PublisherSupportUrl: https://github.com/${GITHUB_REPO}/issues
PackageName: ${q(PACKAGE_NAME)}
PackageUrl: https://github.com/${GITHUB_REPO}
License: MIT
LicenseUrl: https://github.com/${GITHUB_REPO}/blob/main/LICENSE
ShortDescription: ${q('Minecraft launcher for Vanilla, Fabric, Quilt, Forge and NeoForge')}
Description: >-
  A dark-themed Minecraft launcher with isolated instances, a Modrinth content
  manager, offline profiles, a custom Electron bootstrapper and a forced BMCLAPI
  mirror for libraries and assets.
Moniker: verdant
Tags:
  - minecraft
  - launcher
  - fabric
  - forge
  - modrinth
ManifestType: defaultLocale
ManifestVersion: '${MANIFEST_VERSION}'
`

  return [
    { name: `${PACKAGE_IDENTIFIER}.yaml`, content: versionManifest },
    { name: `${PACKAGE_IDENTIFIER}.installer.yaml`, content: installerManifest },
    { name: `${PACKAGE_IDENTIFIER}.locale.ru-RU.yaml`, content: russianLocale },
    { name: `${PACKAGE_IDENTIFIER}.locale.en-US.yaml`, content: englishLocale }
  ].map((file) => ({ ...file, size: installerSize, fileName }))
}

/** SHA-256 of a file, uppercase (the winget manifest convention). */
export async function sha256File(path) {
  const hash = createHash('sha256')
  for await (const chunk of createReadStream(path)) hash.update(chunk)
  return hash.digest('hex').toUpperCase()
}

/** Reads `--flag value` pairs without pulling in a CLI library. */
export function parseArgs(argv) {
  const args = {}
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index]
    if (!arg.startsWith('--')) continue
    const key = arg.slice(2)
    const next = argv[index + 1]
    args[key] = next && !next.startsWith('--') ? (index++, next) : 'true'
  }
  return args
}

const invokedDirectly = process.argv[1]?.endsWith('make-winget-manifest.mjs')
if (invokedDirectly) {
  const args = parseArgs(process.argv.slice(2))
  const version = (args.version ?? '').replace(/^v/, '')
  if (!version) {
    console.error('usage: node scripts/make-winget-manifest.mjs --version 1.2.0 [--sha256 HASH | --from <setup.exe>] [--out dist-winget]')
    process.exit(2)
  }
  const out = args.out ?? 'dist-winget'

  let sha256 = args.sha256?.toUpperCase()
  let installerSize = 0
  if (args.from) {
    sha256 = await sha256File(args.from)
    const { stat } = await import('node:fs/promises')
    installerSize = (await stat(args.from)).size
  }
  if (!sha256 || !/^[0-9A-F]{64}$/.test(sha256)) {
    console.error('нужен --sha256 (64 hex) или --from <путь к Setup.exe>')
    process.exit(2)
  }

  // `winget validate --manifest <dir>` parses *every* file in the folder, so
  // checksums.txt must not live next to the YAML.
  const manifestDir = join(out, 'manifests')
  await mkdir(manifestDir, { recursive: true })
  for (const file of buildManifests({ version, sha256, installerSize })) {
    await writeFile(join(manifestDir, file.name), file.content, 'utf8')
    console.log(`wrote ${join(manifestDir, file.name)}`)
  }
  // sha256sum-compatible file, so the release can verify without winget
  await writeFile(join(out, 'checksums.txt'), `${sha256.toLowerCase()}  ${installerFileName(version)}\n`, 'ascii')
  console.log(`wrote ${join(out, 'checksums.txt')}`)
}
