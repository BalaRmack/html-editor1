export const dictionaries: Record<Language, Record<TKey, string>> = { ru, en }

export function translate(language: Language, key: TKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[language]?.[key] ?? ru[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? ''))
}

export function useT(): (key: TKey, vars?: Record<string, string | number>) => string {
  const language = useAppStore((state) => state.settings.language)
  return useMemo(() => (key: TKey, vars?: Record<string, string | number>) => translate(language, key, vars), [language])
}

/**
 * Russian-style plural picker for countable nouns, e.g. `pluralCount(t, 42, 'mod')`
 * → «42 мода». Falls back to the `many` form for other languages.
 */
export function pluralCount(
  t: (key: TKey, vars?: Record<string, string | number>) => string,
  count: number,
  unit: 'mod'
): string {
  const mod100 = Math.abs(count) % 100
  const mod10 = mod100 % 10
  const form: TKey =
    mod100 > 10 && mod100 < 20
      ? (`unit.${unit}.many` as TKey)
      : mod10 === 1
        ? (`unit.${unit}.one` as TKey)
        : mod10 >= 2 && mod10 <= 4
          ? (`unit.${unit}.few` as TKey)
          : (`unit.${unit}.many` as TKey)
  return `${count} ${t(form)}`
}

/** Maps a backend error code (or message) to a localised, human sentence. */
export function localizeError(
  t: (key: TKey, vars?: Record<string, string | number>) => string,
  code?: string,
  vars?: Record<string, string | number>
): string {
  if (!code) return t('errors.unknown')
  const key = `errors.${code}` as TKey
  if (key in ru) return t(key, vars)
  // Fall back to a neutral sentence — never show a raw stack/URL as the message.
  return t('errors.unknown')
}

/** True when the code has a dedicated localised sentence. */
export function hasErrorText(code?: string): boolean {
  return Boolean(code) && (`errors.${code}` as TKey) in ru
}
